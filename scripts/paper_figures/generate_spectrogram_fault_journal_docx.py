"""
Build a journal-style Methods and Results Word document for spectrogram-image fault classification.

Embeds figures from src/paper_assets/figures/ (generated by generate_spectrogram_fault_figures.py)
and validation plots from the anchor run mirror under from_anchor_run_20260407_193339/.

Usage (from repository root):
  python scripts/paper_figures/generate_spectrogram_fault_journal_docx.py
  python scripts/paper_figures/generate_spectrogram_fault_journal_docx.py --output docs/MyTitle.docx

Requires: pip install python-docx
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _load_json(path: Path) -> dict:
    if not path.is_file():
        return {}
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def _add_caption_para(doc, text: str, *, italic: bool = True) -> None:
    from docx.shared import Pt
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(9)
    r.italic = italic
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER


def _add_figure(doc, image_path: Path, width_inches: float = 6.2) -> bool:
    from docx.shared import Inches
    from docx.enum.text import WD_ALIGN_PARAGRAPH

    if not image_path.is_file():
        p = doc.add_paragraph(f"[Missing figure: {image_path}]")
        p.runs[0].italic = True
        return False
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    run.add_picture(str(image_path.resolve()), width=Inches(width_inches))
    return True


def build_document(
    output_path: Path,
    *,
    anchor_name: str = "from_anchor_run_20260407_193339",
) -> None:
    try:
        from docx import Document
        from docx.shared import Pt, RGBColor
        from docx.enum.text import WD_ALIGN_PARAGRAPH
    except ImportError as e:
        raise SystemExit(
            "python-docx is required. Install with: pip install python-docx"
        ) from e

    root = _repo_root()
    fig_dir = root / "src" / "paper_assets" / "figures"
    anchor_dir = fig_dir / anchor_name

    cfg = _load_json(anchor_dir / "config.json")
    met = _load_json(anchor_dir / "metrics.json")

    doc = Document()

    title = doc.add_heading(
        "Spectrogram-Image Fault Classification: Methods and Results", level=0
    )
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER

    sub = doc.add_paragraph()
    run = sub.add_run(
        "Supervised deep learning on folder-organized spectrogram PNGs (MIMII-style corpus); "
        "anchor experiment with group-aware validation and ImageNet-transfer CNN."
    )
    run.font.size = Pt(11)
    run.font.color.rgb = RGBColor(0x44, 0x44, 0x44)
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER

    doc.add_paragraph()

    # ----- METHODS (narrative, journal-style) -----
    doc.add_heading("Methods", level=1)

    p1 = doc.add_paragraph()
    p1.add_run(
        "Task definition and data source. "
        "Industrial machine-health monitoring was framed as a supervised image-classification problem on "
        "two-dimensional time–frequency representations stored as PNG files. "
        "Images and discrete labels were ingested through a single folder-based dataset class shared with "
        "other experiments in this repository; label cardinality was inferred as one plus the maximum "
        "integer label observed on the training index set so that binary (normal versus abnormal) and "
        "multiclass extensions are handled uniformly. "
        "For the primary analysis documented here, all available signal-to-noise ratio (SNR) folders under "
        "the spectrogram root were pooled, and the model was trained to discriminate two classes on the "
        "resulting union of files. "
    )
    if cfg.get("dataset_path"):
        p1.add_run(
            f"The on-disk spectrogram root used for the anchor run was {cfg.get('dataset_path')!s}. "
        )
    if cfg.get("n_train") is not None and cfg.get("n_val") is not None:
        p1.add_run(
            f"After the train–validation partition described below, {int(cfg['n_train']):,} spectrograms "
            f"were used for parameter updates and {int(cfg['n_val']):,} were held out for model selection "
            f"and reporting (Fig. 1). "
        )

    p2 = doc.add_paragraph()
    p2.add_run(
        "Preprocessing and augmentation. "
        "Every image was resized to a square of 224 pixels on the side and converted to a three-channel "
        "tensor, then normalized with ImageNet channel means and standard deviations so that off-the-shelf "
        "ImageNet-pretrained convolutional backbones could be applied without ad hoc rescaling. "
        "Validation used only this deterministic preprocessing chain. "
        "Training applied a fixed “strong” augmentation preset: small random affine translation and scale, "
        "mild color jitter, two frequency-mask bands and two time-mask bands (each mask occupying up to "
        "20% of the respective axis), stochastic time shifting up to 8% of the time axis, and additive "
        "Gaussian noise on the tensor (standard deviation 0.01 after normalization). "
        "These tensor-space masks follow the SpecAugment spirit used in speech and audio representation learning. "
    )

    p3 = doc.add_paragraph()
    p3.add_run(
        "Train–validation split and control of group leakage. "
        "Twenty percent of samples were reserved for validation, with per-class stratification on the label. "
        "Whenever the dataset exposed a non-trivial grouping variable (for example machine identity or "
        "session key derived from the directory layout), the first fold of a stratified group k-fold split "
        "was used so that no group appeared in both training and validation; this reduces optimistic bias "
        "relative to an independent and identically distributed assumption across files. "
        "The anchor run enabled this group-aware mode. "
        "The same split logic can be disabled for ablation by turning off the group-stratified option in the "
        "training entry point. "
    )

    p4 = doc.add_paragraph()
    p4.add_run(
        "Neural network family and anchor architecture. "
        "Models were instantiated through a single factory that wraps the timm library. "
        "The anchor configuration used a ResNet-50 backbone without global pooling inside timm "
        "(global pooling disabled so that spatial feature maps remain available), followed by global "
        "average pooling over height and width and a fully connected classifier to two logits. "
        "Optionally, the same code path supports a convolutional backbone followed by a CBAM-style spatial "
        "attention gate on the last feature map before pooling, and a hybrid in which the feature map is "
        "vectorized into a token grid, projected to a transformer width, augmented with learned or "
        "two-dimensional sinusoidal positional encodings and an optional class token, and passed through "
        "a small stack of pre-norm Transformer encoder layers before the final linear head (Fig. 2–4). "
        "Those variants were not used for the anchor run but are retained in the implementation for "
        "comparative experiments. "
    )

    p5 = doc.add_paragraph()
    p5.add_run(
        "Loss, optimization, and stopping. "
        "Training minimized a class-weighted cross-entropy in which each class weight was proportional to "
        "the inverse of its frequency on the training indices only, so that minority-class gradients were "
        "up-weighted without using validation statistics. "
        "Optimization used AdamW with learning rate 1\u00d710\u207b\u2074, weight decay 0.05, linear learning-rate warmup "
        "over three epochs followed by cosine decay, automatic mixed precision on CUDA hardware when "
        "available, and global gradient norm clipping at 1.0. "
        "The best checkpoint on validation balanced accuracy was retained; training terminated early if "
        "balanced accuracy did not improve for fifteen consecutive epochs. "
    )

    p6 = doc.add_paragraph()
    p6.add_run(
        "Evaluation metrics and interpretability exports. "
        "The held-out validation split was scored with accuracy, macro-averaged precision, recall, and F1, "
        "Matthews correlation coefficient, Cohen’s kappa, sensitivity and specificity, positive and negative "
        "predictive values, area under the receiver-operating-characteristic curve, area under the "
        "precision–recall curve, Brier score, and expected calibration error, in addition to balanced accuracy. "
        "Figures for training dynamics, scalar curves, the ROC, and the confusion matrix were written "
        "automatically at the end of training. "
        "For convolutional models that expose the backbone module, gradient-weighted class activation "
        "mapping (Grad-CAM) was applied to a small number of validation examples for qualitative review. "
    )

    doc.add_heading("Figure panels (methods)", level=2)
    figs_methods = [
        (fig_dir / "methodology_pipeline.png", "Fig. 1. End-to-end pipeline from spectrogram folders to metrics."),
        (fig_dir / "architecture_cnn_baseline.png", "Fig. 2. CNN baseline used for the anchor run (ResNet-50, timm)."),
        (fig_dir / "architecture_cnn_spatial_attention.png", "Fig. 3. Optional spatial-attention variant (cnn_se)."),
        (fig_dir / "architecture_cnn_transformer_hybrid.png", "Fig. 4. Optional CNN–Transformer hybrid (cnn_transformer)."),
    ]
    for path, cap in figs_methods:
        _add_figure(doc, path)
        _add_caption_para(doc, cap)

    # ----- RESULTS -----
    doc.add_heading("Results", level=1)

    if met:
        bal = met.get("val_balanced_accuracy", 0.0)
        acc = met.get("accuracy", 0.0)
        mp, mr, mf = (
            met.get("macro_precision", 0.0),
            met.get("macro_recall", 0.0),
            met.get("macro_f1", 0.0),
        )
        auc = met.get("auc_roc", 0.0)
        sens, spec = met.get("sensitivity", 0.0), met.get("specificity", 0.0)
        mcc = met.get("mcc", 0.0)
        tsec = met.get("train_time_sec", 0.0)
        pr = doc.add_paragraph()
        pr.add_run(
            f"Anchor run on the held-out validation partition (n = {int(cfg.get('n_val', 0)):,} images) "
            f"achieved a balanced accuracy of {bal:.4f}, overall accuracy of {acc:.4f}, and macro-averaged "
            f"precision, recall, and F1 of {mp:.4f}, {mr:.4f}, and {mf:.4f}, respectively. "
            f"Discrimination was strong by ROC analysis (AUC = {auc:.4f}), with sensitivity {sens:.4f} and "
            f"specificity {spec:.4f}. Matthews correlation coefficient was {mcc:.4f}. "
            f"Total wall-clock training time for this run was approximately {tsec / 3600:.2f} hours on the "
            f"machine used for execution (Fig. 5–8). "
        )
    else:
        doc.add_paragraph(
            "[metrics.json not found next to figures; paste validation metrics after copying the anchor run bundle.]"
        )

    doc.add_heading("Figure panels (results)", level=2)
    figs_res = [
        (anchor_dir / "training_curves.png", "Fig. 5. Training loss and validation balanced accuracy by epoch."),
        (anchor_dir / "metric_curves.png", "Fig. 6. Validation macro precision, recall, and F1 by epoch."),
        (anchor_dir / "roc_curve.png", "Fig. 7. Receiver operating characteristic curve on the validation split."),
        (anchor_dir / "confusion_matrix.png", "Fig. 8. Confusion matrix on the validation split."),
        (anchor_dir / "grad_cam_0.png", "Fig. 9. Representative Grad-CAM overlay on a validation spectrogram (example 1 of 4 saved)."),
    ]
    for path, cap in figs_res:
        _add_figure(doc, path, width_inches=5.8 if "grad_cam" in path.name else 6.0)
        _add_caption_para(doc, cap)

    doc.add_heading("Implementation and reproducibility", level=1)
    pr2 = doc.add_paragraph()
    pr2.add_run(
        "Training was invoked with the repository entry point "
        "`python -m experiments.train_spectrogram_fault` from the `src` directory; "
        "hyperparameters for the anchor run are stored in `config.json` alongside `metrics.json` in the "
        "run output folder. "
        "Figure schematics can be regenerated with `python scripts/paper_figures/generate_spectrogram_fault_figures.py`. "
        "Dependencies are listed in `src/requirements.txt`, including the timm package for pretrained backbones. "
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(output_path))
    print("Wrote:", output_path.resolve())


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Output .docx path (default: docs/Spectrogram_Fault_Methods_and_Results.docx)",
    )
    parser.add_argument(
        "--anchor-dir-name",
        type=str,
        default="from_anchor_run_20260407_193339",
        help="Subfolder of src/paper_assets/figures/ containing copied run plots and JSON.",
    )
    args = parser.parse_args()
    root = _repo_root()
    out = args.output or (root / "docs" / "Spectrogram_Fault_Methods_and_Results.docx")
    build_document(out, anchor_name=args.anchor_dir_name)


if __name__ == "__main__":
    os.environ.setdefault("MPLBACKEND", "Agg")
    main()
